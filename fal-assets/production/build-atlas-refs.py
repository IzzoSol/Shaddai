#!/usr/bin/env python
"""Rebuild production/atlas-refs.js: every image under fal-assets/refs/ mapped to its realm by filename prefix.
Run after filing new references: python fal-assets/production/build-atlas-refs.py"""
import os, json
HERE = os.path.dirname(os.path.abspath(__file__)); REFS = os.path.join(os.path.dirname(HERE), 'refs')
RULES = [  # (substring in path, realm id) — first match wins
  ('quill-library', 'forest'), ('dragon-red', 'volcano'), ('dragon-blue', 'arctic'), ('dragon-tan', 'desert'), ('dragon-green', 'forest'), ('dragon-breath', 'volcano'),
  ('colosseum', 'colosseum'), ('emberfall', 'volcano'), ('darkforest', 'darkforest'), ('crystal-sea', 'ocean'), ('arctic', 'arctic'), ('desert', 'desert'),
  ('meadow', 'meadow'), ('home-', 'meadow'), ('terraced', 'meadow'), ('suburb', 'suburb'), ('forest', 'forest'), ('void', 'void'),
  ('wild-', 'wilds'), ('pass-', 'wilds'), ('city-', 'grid'), ('bazaar', 'grid'), ('grand-hall', 'grid'), ('nexus-code', 'grid'), ('hub-and', 'grid'), ('realm-map', 'grid'),
  ('furniture', 'grid'), ('npc-', 'grid'), ('hero-goggles', 'grid'), ('sky-skate', 'grid'), ('props-rock', 'wilds'), ('fantasy-biomes', 'wilds'),
]
out = {}
for root, _, files in os.walk(REFS):
  for f in sorted(files):
    if not f.lower().endswith(('.png', '.jpg', '.jpeg', '.webp')): continue
    rel = os.path.relpath(os.path.join(root, f), os.path.dirname(REFS)).replace(os.sep, '/')
    realm = next((r for k, r in RULES if k in f.lower()), None)
    if realm: out.setdefault(realm, []).append(rel)
open(os.path.join(HERE, 'atlas-refs.js'), 'w', encoding='utf-8').write('// generated by build-atlas-refs.py — do not edit\nwindow.ATLAS_REFS = ' + json.dumps(out, indent=1) + ';\n')
print({k: len(v) for k, v in sorted(out.items())})
