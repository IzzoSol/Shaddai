const vm = require('vm'), fs = require('fs');
const THREE = require('../ual/node_modules/three/build/three.cjs');
let ok = 0, bad = 0;
function t(n, c) { c ? ok++ : (bad++, console.log('FAIL', n)); }
const store = {}; let sparks = 0, spent = [];
const ctx = { console, THREE, localStorage: { getItem: k => store[k] || null, setItem: (k, v) => store[k] = v }, ShdSparks: { get: () => sparks, spend: (n, k, id) => { if (sparks < n) return false; sparks -= n; spent.push([k, id, n]); return true; } } };
ctx.window = ctx; vm.createContext(ctx);
vm.runInContext(fs.readFileSync('public/world-gear.js', 'utf8'), ctx);
const G = ctx.WorldGear;
t('no shield: damage unchanged', G.absorb(40) === 40);
t('cannot buy without Sparks', !G.buy('buckler').ok && G.owned().length === 0);
sparks = 5000;
t('buy buckler charges 150 and auto-equips', G.buy('buckler').ok && sparks === 4850 && G.state().equipped.shield === 'buckler');
t('buckler -15%: 40 -> 34', G.absorb(40) === 34);
t('never reduces a landed hit below 1', G.absorb(1) === 1);
t('cannot buy twice', !G.buy('buckler').ok);
t('upgrade L1->L2 costs 200 and gives -20%', G.upgrade('buckler').ok && sparks === 4650 && Math.abs(G.state().reduction - 0.2) < 1e-9 && G.absorb(100) === 80);
t('upgrade to L3, then max', G.upgrade('buckler').ok && !G.upgrade('buckler').ok && Math.abs(G.state().reduction - 0.25) < 1e-9);
t('tower shield is stronger: -30%', G.buy('tower').ok && G.equip('tower').ok && G.absorb(100) === 70);
G.buy('aegis'); G.equip('aegis');
let st = G.state(); t('aegis barrier full at 60', st.barrierMax === 60 && st.barrier === 60);
t('barrier soaks a 40 hit completely', G.absorb(40) === 0 && Math.round(G.state().barrier) === 20);
t('barrier overflow passes through: 50 -> 30 after 20 soaked', G.absorb(50) === 30 && G.state().barrier === 0);
G.tick(10); t('no recharge before 25 s untouched', G.state().barrier === 0);
G.tick(16); G.tick(3); t('recharges once left alone for 25 s', G.state().barrier > 0);
for (let i = 0; i < 20; i++) G.tick(1); t('recharge caps at max', Math.abs(G.state().barrier - 60) < 1e-6);
t('aegis upgrade raises the barrier to 80', G.upgrade('aegis').ok && G.state().barrierMax === 80 && G.state().barrier === 80);
t('cosmetics do not upgrade and do not touch stats', G.buy('halo').ok && !G.upgrade('halo').ok && G.state().barrierMax === 80);
t('one item per slot: equipping another halo swaps', G.buy('halo-void').ok && G.equip('halo-void').ok && G.state().equipped.halo === 'halo-void');
G.unequip('shield'); t('unequip shield -> full damage', G.absorb(40) === 40);
t('ledger entries are tagged', spent.every(s => s[0] === 'gear' || s[0] === 'gear-up'));
t('persists equipped + owned', JSON.parse(store.shd_gear_v1).owned.aegis === 2);
const scene = new THREE.Scene(), av = new THREE.Group(); av.position.set(5, 0, 7);
const V = G.buildVisuals({ THREE, scene, getAvatar: () => av });
G.equip('aegis'); V.update(0.016);
t('visuals follow the avatar and show the barrier', V.group.position.x === 5 && V.group.children.some(c => c.visible));
G.absorb(10); V.update(0.016); t('hit flash brightens the barrier', V.group.children.some(c => c.material && c.material.opacity > 0.3));
V.dispose(); t('visuals dispose', !scene.children.includes(V.group));
console.log(bad ? 'FAIL' : 'ok', ok, 'pass'); process.exit(bad ? 1 : 0);
