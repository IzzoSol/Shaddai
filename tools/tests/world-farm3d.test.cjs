const vm = require('vm'), fs = require('fs');
const THREE = require('../ual/node_modules/three/build/three.cjs');
let ok = 0, bad = 0;
function t(n, c) { c ? ok++ : (bad++, console.log('FAIL', n)); }
const store = {};
const ctx = { console, THREE, localStorage: { getItem: k => store[k] || null, setItem: (k, v) => store[k] = v }, ShdSparks: { spend: () => true, add() { } } };
ctx.window = ctx; vm.createContext(ctx);
for (const f of ['world-inventory.js', 'world-farm.js', 'world-farm3d.js']) vm.runInContext(fs.readFileSync('public/' + f, 'utf8'), ctx);
let now = 1e12; ctx.WorldFarm._now(() => now); ctx.WorldFarm._reset();
const scene = new THREE.Scene();
const F = ctx.buildFarm3D({ THREE, scene, heightAt: () => 0, getPlayer: () => ({ pos: { x: 0, z: 0 } }) });
const beds = F.group.children.filter(c => c.isGroup);
t('6 beds', beds.length === 6);
t('empty hidden', beds.every(b => b.children.filter(c => c.isMesh && c.geometry.type === 'ConeGeometry').every(p => !p.visible)));
ctx.WorldFarm.plant(0, 'bean'); now += 150e3; F.update(2);
const pl = beds[0].children.filter(c => c.geometry.type === 'ConeGeometry');
t('growing visible', pl.every(p => p.visible) && pl[0].scale.x > 0.25 && pl[0].scale.x < 1);
now += 200e3; F.update(2);
t('ripe turns gold', pl[0].material.emissiveIntensity > 0.5);
t('beds placed near plot SW', F.pos.x < 0 && F.pos.z > 0);
F.dispose(); t('disposed', !scene.children.includes(F.group));
console.log(bad ? 'FAIL' : 'ok', ok, 'pass'); process.exit(bad ? 1 : 0);
