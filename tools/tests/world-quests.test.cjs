const vm = require('vm'), fs = require('fs');
let ok = 0, bad = 0;
function t(n, c) { c ? ok++ : (bad++, console.log('FAIL', n)); }
const store = {}, sp = [];
const ctx = { console, setInterval: () => 0, clearInterval() { }, localStorage: { getItem: k => store[k] || null, setItem: (k, v) => store[k] = v }, ShdSparks: { add: n => sp.push(n) } };
ctx.window = ctx; vm.createContext(ctx);
vm.runInContext(fs.readFileSync('public/world-quests.js', 'utf8'), ctx);
const Q = ctx.WorldQuests;
let d = Q.today();
t('3 quests', d.length === 3);
t('distinct kinds', new Set(d.map(q => q.kind)).size === 3);
const k = d[0];
Q.note(k.kind, k.need);
t('done', Q.today()[0].done);
t('claim pays', Q.claim(0).ok && sp[0] === k.reward);
t('no double claim', !Q.claim(0).ok);
t('unfinished not claimable', !Q.claim(1).ok);
let day = Date.parse('2026-10-05T12:00:00Z');
Q._now(() => day);
Q.note(Q.today()[0].kind, 99);
day = Date.parse('2026-10-06T12:00:00Z');
t('daily reset', Q.today().every(q => q.have === 0 && !q.claimed));
console.log(bad ? 'FAIL' : 'ok', ok, 'pass');
process.exit(bad ? 1 : 0);
