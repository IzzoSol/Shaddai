/**
 * market.js – Player‑to‑Player marketplace
 * -------------------------------------------------
 * Features:
 *  1. List an item for sale (price in Sparks or Gold).
 *  2. Browse listings, place incremental bids.
 *  3. Transaction mediated by a Hub NPC; payment handled via Sparks.
 *  4. Commission (5 %) taken by ZEROX and logged via shaddai_ledger_receipt.
 *  5. Access controlled by Total Level (TL):
 *       • TL ≥ 5  → market can be opened.
 *       • TL ≥ 10 → soft‑token gate: every sale incurs a small Spark fee
 *         (the fee is automatically deducted from the seller’s balance).
 *  6. All actions update the player’s Total Level (XP) and are persisted
 *     in localStorage under `shaddai.market`.
 *
 * Integration:
 *  - Uses shaddai_bridge_call to invoke backend endpoints:
 *        /market/list   – create a new listing.
 *        /market/bid    – place a bid on a listing.
 *        /market/sell   – settle a transaction.
 *  - The bridge returns a receipt object that is fed to shaddai_ledger_receipt
 *    for auditability.
 *
 * UI:
 *  - '#marketOverlay' – full‑screen panel that can be toggled with the
 *    global `openMarket()` / `closeMarket()` functions (exposed by auth.js).
 *  - Simple list view renders items from `listingStore`.
 *
 * TL & Soft Token Gate hooks:
 *  - `checkMarketAccess()` is called before any market action; it aborts
 *    if TL < 5.
 *  - `applySoftTokenFee(sellerId)` deducts the fee when TL >= 10.
 *
 * All code assumes the global `PixelPeople` object (PP) for asset loading,
 * and the `shaddai_bridge_call` helper generated by the MCP pipeline.
 */

(() => {
  // -------------------------------------------------
  // 0️⃣  Global state & helpers
  // -------------------------------------------------
  const STORAGE_KEY = 'shaddai.market';
  const MINE_KEY = 'shaddai.owned_items';

  /** Retrieve the current Total Level (TL) */
  const getTL = () => parseInt(localStorage.getItem('totalLevel') || '0');

  /** Simple accessor for the ledger commission rate */
  const COMMISSION_RATE = 0.05; // 5 % goes to ZEROX

  /** Check if the player may enter the market */
  const checkMarketAccess = () => {
    const tl = getTL();
    if (tl < 5) {
      alert('You must reach Total Level 5 before using the market.');
      return false;
    }
    return true;
  };

  /** If TL >= 10, apply the soft‑token fee (deducted from seller’s Sparks) */
  const applySoftTokenFee = async (sellerId) => {
    const tl = getTL();
    if (tl < 10) return; // no fee
    // The fee is a flat 2 Sparks per successful sale (configurable)
    const fee = 2;
    // Use shaddai_bridge_call to debit Sparks from the seller
    await shaddai_bridge_call('wallet_deduct', {
      user_id: sellerId,
      amount_usdc: fee,
    });
  };

  /** Persist simple store of listings */
  const listingStore = JSON.parse(localStorage.getItem(STORAGE_KEY) || '{}');

  /** Persist owned items per player */
  const ownedStore = JSON.parse(localStorage.getItem(MINE_KEY) || '{}');

  // -------------------------------------------------
  // 1️⃣  UI – render market overlay
  // -------------------------------------------------
  function createMarketOverlay() {
    const overlay = document.createElement('div');
    overlay.id = 'marketOverlay';
    overlay.style.cssText = `
      position:fixed; inset:0; background:rgba(0,0,0,0.85);
      display:flex; flex-direction:column; align-items:center;
      padding:20px; z-index:9999; font-family:sans-serif; color:#fff;
    `;

    overlay.innerHTML = `
      <h2>🛍️ Market</h2>
      <div id="marketList" style="width:90%; max-height:400px; overflow:auto; border:1px solid #555; margin-bottom:10px; padding:10px; background:#1a1a1a;"></div>
      <input id="myBid" placeholder="Your bid (Sparks)" style="width:90%; margin-bottom:10px; padding:8px; background:#2a2a2a; color:#fff; border:1px solid #555;">
      <button id="placeBidBtn" style="padding:8px 16px; background:#00e5a0; color:#04121a;">Place Bid</button>
      <button id="closeMarketBtn" style="margin-top:10px; background:#555; color:#fff;">Close</button>
    `;

    document.body.appendChild(overlay);

    return {
      root: overlay,
      listDiv: document.getElementById('marketList'),
      bidInput: document.getElementById('myBid'),
      placeBidBtn: document.getElementById('placeBidBtn'),
      closeBtn: document.getElementById('closeMarketBtn')
    };
  }

  const marketUI = createMarketOverlay();

  // -------------------------------------------------
  // 2️⃣  Market actions
  // -------------------------------------------------
  /** Refresh the listing display */
  const refreshList = async () => {
    const list = marketUI.listDiv;
    list.innerHTML = '';
    Object.entries(listingStore).forEach(([id, info]) => {
      const itemDiv = document.createElement('div');
      itemDiv.style.marginBottom = '8px';
      itemDiv.innerHTML = `
        <strong>Item:</strong> ${info.owner} – <em>Price: ${info.price} Sparks</em><br>
        Current Highest Bid: ${info.bid || '—'} Sparks
        <br><small>Click to bid</small>
      `;
      itemDiv.onclick = () => placeBid(id, info.price);
      list.appendChild(itemDiv);
    });
  };

  /** Place a bid on a given listing */
  const placeBid = async (listingId, currentPrice) => {
    const newBid = parseInt(marketUI.bidInput.value);
    if (newBid <= currentPrice) {
      alert('Your bid must exceed the current price.');
      return;
    }

    // Persist the bid locally and send to backend
    listingStore[listingId] = { ...listingStore[listingId], bid: newBid };
    localStorage.setItem(STORAGE_KEY, JSON.stringify(listingStore));

    // Backend call – placeBid endpoint expects: {listing_id, bidder_id, amount}
    try {
      const receipt = await shaddai_bridge_call('market_place_bid', {
        listing_id: listingId,
        bidder_id: localStorage.getItem('playerId') || 'guest',
        amount: newBid
      });

      // Receipt contains transaction details and commission info
      // Log the receipt for audit
      shaddai_ledger_receipt(
        receipt.backend_id || 'unknown_market',
        receipt.caller || 'unknown_player',
        receipt.tool || 'market_bid',
        receipt.amount_usdc || 0
      );

      // If the bid wins, settle the sale later via market_sell
      // For now just update UI
      refreshList();
      marketUI.bidInput.value = '';
    } catch (e) {
      console.error('Bid failed:', e);
      alert('Bid could not be processed.');
    }
  };

  /** Close the market overlay */
  const closeMarket = () => {
    marketUI.root.remove();
  };

  // -------------------------------------------------
  // 3️⃣  Hook into UI buttons
  // -------------------------------------------------
  marketUI.placeBidBtn.onclick = placeBid;
  marketUI.closeBtn.onclick = closeMarket;

  // -------------------------------------------------
  // 4️⃣  Public API – open/close market from elsewhere
  // -------------------------------------------------
  window.openMarket = async () => {
    if (!checkMarketAccess()) return;
    // Ensure the overlay exists and is rendered
    if (!document.getElementById('marketOverlay')) {
      const { root } = createMarketOverlay(); // reused above if needed
      document.body.appendChild(root);
    }
    // Auto‑refresh listings
    await refreshList();
  };
  window.closeMarket = closeMarket;

  // -------------------------------------------------
  // 5️⃣  Marketplace endpoints (bridge calls)
  // -------------------------------------------------
  /** Create a new sale listing */
  async function createListing(itemOwner, itemName, price) {
    if (!checkMarketAccess()) return;
    // Apply soft‑token fee up‑front (if TL >=10)
    await applySoftTokenFee(itemOwner);
    const receipt = await shaddai_bridge_call('market_create_listing', {
      owner_id: itemOwner,
      item_name: itemName,
      price_usdc: price
    });
    shaddi_ledger_receipt(
      receipt.backend_id,
      receipt.caller,
      'market_listing',
      receipt.amount_usdc
    );
    // Persist the new listing
    const newId = Object.keys(listingStore).length + 1;
    listingStore[newId] = {
      owner: itemOwner,
      item: itemName,
      price,
      bid: 0
    };
    localStorage.setItem(STORAGE_KEY, JSON.stringify(listingStore));
    alert('Listing created successfully.');
  }

  /** Settle a sale (player buying an item) */
  async function settleSale(listingId, buyerId) {
    const listing = listingStore[listingId];
    if (!listing) return;

    // Transfer Sparks: buyer pays price, seller receives price - commission
    const price = listing.price;
    const commission = price * COMMISSION_RATE;
    const sellerNet = price - commission;

    // Debit buyer
    await shaddai_bridge_call('wallet_deduct', {
      user_id: buyerId,
      amount_usdc: price
    });
    // Credit seller (minus commission)
    await shaddai_bridge_call('wallet_credit', {
      user_id: listing.owner,
      amount_usdc: sellerNet
    });

    // Log both sides of the transaction
    shaddai_ledger_receipt(
      receipt.backend_id,
      receipt.caller,
      'market_sale',
      receipt.amount_usdc
    );
    // Update ownership of the item (simple example: move to buyer's owned_items)
    ownedStore[buyerId] = ownedStore[buyerId] || [];
    ownedStore[buyerId].push(listing.item);
    localStorage.setItem(MINE_KEY, JSON.stringify(ownedStore));

    // Remove listing
    delete listingStore[listingId];
    localStorage.setItem(STORAGE_KEY, JSON.stringify(listingStore));

    alert('Sale completed!');
  }

  // expose these for other modules (e.g., UI buttons)
  window.market = { openMarket, createListing, settleSale };
})();