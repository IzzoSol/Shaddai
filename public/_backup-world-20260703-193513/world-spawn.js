    function startSkydive() {
      _state = 'skydive';
      _skyT  = 0;
      camera.position.set(SKY_ORBIT_R, SKY_ALT, 0);
      _lookAt.set(0, 0, 0);
      camera.lookAt(_lookAt);
    }

    function openPicker() {
      _buildPickerDOM();
      _pickerEl.style.display = 'flex';
      // Free the mouse so the picker is clickable (no need to press ESC first).
      try { if (document.exitPointerLock) document.exitPointerLock(); } catch (e) {}
      try { document.body.style.cursor = 'default'; _pickerEl.style.cursor = 'default'; } catch (e) {}
    }

    function pickPortal(code) {
      var portal = null;
      for (var i = 0; i < portals.length; i++) {
        if (portals[i].code === code) { portal = portals[i]; break; }
      }
      if (!portal) {
        console.warn('world-spawn: unknown portal code "' + code + '"');
        return;
      }
      _targetCode = code;

      if (_pickerEl) _pickerEl.style.display = 'none';

      var px = portal.pos[0], pz = portal.pos[1];
      var gy = groundAt(px, pz);

      var _cd  = Math.hypot(px, pz);
      var _off = 84;
      var landX, landZ;
      if (_cd < 1) { landX = px; landZ = pz + _off; }
      else { landX = px - (px / _cd) * _off; landZ = pz - (pz / _cd) * _off; }
      var eyeY = gy + 2.2;

      playerPos.x = landX;
      playerPos.z = landZ;

      _camStart.copy(camera.position);
      _rotFrom.copy(camera.quaternion);

      _camEnd.set(landX, eyeY, landZ);

      camera.position.copy(_camEnd);
      _lookAt.set(px, eyeY + 4, pz);
      camera.lookAt(_lookAt);
      _rotTo.copy(camera.quaternion);

      camera.position.copy(_camStart);
      camera.quaternion.copy(_rotFrom);

      // ── Cinematic arc setup (computed once here; update() only reads these) ──
      // Horizontal travel vector start→end. The swoop bulges sideways (perpendicular)
      // and lifts slightly at the apex, so the fall reads as a graceful curve rather
      // than a straight plummet — settling exactly on _camEnd at ease=1.
      var _dx = _camEnd.x - _camStart.x;
      var _dz = _camEnd.z - _camStart.z;
      var _dl = Math.hypot(_dx, _dz) || 1;
      _arcAxis.set(-_dz / _dl, 0, _dx / _dl);        // left/right of the path
      _bankAxis.set(_dx / _dl, 0, _dz / _dl);        // along the path (roll axis)
      _arcMag  = Math.min(34, _dl * 0.16);           // subtle, distance-scaled, capped
      _arcRise = Math.min(9, _dl * 0.05);            // gentle apex lift

      _descT = 0;
      _state = 'descent';
    }

    /**
     * update(dt, t)
     * Drives portal marker animations and the active camera tween.
     * Zero per-frame heap allocations: all math writes to pre-existing objects/typed-arrays.
     */
    function update(dt, t) {

      // ── Portal marker animations ──────────────────────────────────────────
      for (var i = 0; i < portalMarkers.length; i++) {
        var m   = portalMarkers[i];
        var phi = t * 1.3 + m.phase;

        // Base pulse (slow breathe)
        var pulse = 0.70 + 0.30 * Math.sin(phi);
        // Vortex shimmer (two layered fast oscillations)
        var shimmer = 0.13 + 0.07 * Math.sin(phi * 2.1 + 0.7) + 0.04 * Math.sin(phi * 3.7);

        // ── Counter-rotating inner tech rings ────────────────────────────
        m.innerRing.rotation.z  += dt * 0.38;
        m.innerGlow.rotation.z   = m.innerRing.rotation.z;  // sync glow to ring
        m.innerRing2.rotation.z -= dt * 0.55;

        // ── Vortex polygon planes (each at unique speed + direction) ─────
        m.vortex0.rotation.z += dt * 0.24;
        m.vortex1.rotation.z -= dt * 0.33;
        m.vortex2.rotation.z += dt * 0.17;

        // ── Opacity pulsing ──────────────────────────────────────────────
        m.pilMat.opacity       = 0.68 + 0.22 * pulse;
        m.pilGlowMat.opacity   = 0.08 + 0.09 * Math.sin(phi * 1.1);
        m.linMat.opacity       = 0.42 + 0.32 * Math.sin(phi * 0.9 + 0.55);
        m.innerGlowMat.opacity = 0.05 + 0.06 * pulse;
        m.fieldMat.opacity     = shimmer;
        m.fieldGlowMat.opacity = 0.05 + 0.04 * Math.sin(phi * 0.8 + 1.2);
        m.discMat.opacity      = pulse * 0.12;
        m.floorRingMat.opacity = 0.05 + 0.04 * Math.sin(phi * 0.72);

        // Concentric rings: staggered phases create depth ripple effect
        m.concMat0.opacity = 0.09 + 0.08 * Math.sin(phi * 1.4 + 0.0);
        m.concMat1.opacity = 0.06 + 0.07 * Math.sin(phi * 1.4 + 0.9);
        m.concMat2.opacity = 0.04 + 0.05 * Math.sin(phi * 1.4 + 1.8);

        // ── Point light breathing ────────────────────────────────────────
        m.light.intensity = 1.3 + 1.0 * Math.sin(phi * 1.05);

        // ── Particle spiral ──────────────────────────────────────────────
        // Writes to pre-allocated Float32Array; no `new` on hot path.
        var posArr = m.particlePositions;
        var tmod   = t * 0.52 + m.phase;
        for (var j = 0; j < N_PARTICLES; j++) {
          var jAng = m.particleAngles[j] + tmod * m.particleSpeeds[j];
          var jR   = m.particleRadii[j] * (0.42 + 0.58 * (0.5 + 0.5 * Math.sin(tmod * 1.1 + j * 1.37)));
          posArr[j * 3]     = Math.cos(jAng) * jR;
          posArr[j * 3 + 1] = RING_Y + Math.sin(jAng) * jR;
          posArr[j * 3 + 2] = Math.sin(tmod * 2.2 + j * 0.74) * 0.28;
        }
        m.particleGeo.attributes.position.needsUpdate = true;
      }

      // ── Sky-dive orbit ────────────────────────────────────────────────────
      if (_state === 'skydive') {
        _skyT += dt;
        var ang = _skyT * SKY_ORBIT_W;
        camera.position.x = Math.cos(ang) * SKY_ORBIT_R;
        camera.position.y = SKY_ALT + Math.sin(_skyT * 0.09) * 14;
        camera.position.z = Math.sin(ang) * SKY_ORBIT_R;
        _lookAt.set(
          Math.cos(ang + 0.35) * 18,
          0,
          Math.sin(ang + 0.35) * 18
        );
        camera.lookAt(_lookAt);
        return;
      }

      // ── Descent tween ─────────────────────────────────────────────────────
      if (_state === 'descent') {
        _descT += dt / DESCEND_SEC;

        if (_descT >= 1) {
          _descT = 1;
          _state = 'idle';

          camera.position.copy(_camEnd);
          camera.quaternion.copy(_rotTo);

          try { controls.lock(); } catch (e) { /* pointer lock may be blocked by browser */ }
          onArrive(_targetCode, _chosenChar);
          return;
        }

        var ease  = smoothstep(_descT);
        // swoop: 0 → 1 → 0 across the descent (peaks mid-flight), zero at both ends
        var swoop = Math.sin(Math.PI * ease);

        camera.position.lerpVectors(_camStart, _camEnd, ease);
        // sideways bulge + apex lift — reuses _arcAxis, no allocation
        camera.position.x += _arcAxis.x * _arcMag * swoop;
        camera.position.z += _arcAxis.z * _arcMag * swoop;
        camera.position.y += _arcRise * swoop;

        // orientation: base look-tween + a whisper of banking that unwinds to 0 on landing
        camera.quaternion.slerpQuaternions(_rotFrom, _rotTo, ease);
        _rollQuat.setFromAxisAngle(_bankAxis, swoop * 0.085);
        camera.quaternion.multiply(_rollQuat);
      }
    }

    function isAnimating() {
      return _state !== 'idle';
    }

    // ── return public API ──
    return {
      startSkydive:  startSkydive,
      openPicker:    openPicker,
      pickPortal:    pickPortal,
      update:        update,
      isAnimating:   isAnimating,
      portalMarkers: portalMarkers,
    };
